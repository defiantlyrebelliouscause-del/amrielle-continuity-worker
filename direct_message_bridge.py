"""Correlation and idempotency helpers for the issue-based message bridge."""
from datetime import datetime, timezone
import os

def current_request_id():
    return str(os.getenv("AMRIELLE_DIRECT_MESSAGE_ID", "")).strip()

def build_message_envelope():
    message = " ".join(os.getenv("AMRIELLE_DIRECT_MESSAGE", "").replace("/run-amrielle", "").split())[:6000]
    request_id = current_request_id()
    if not (request_id and message):
        return None
    return {
        "request_id": request_id,
        "source": "github_issue_comment" if os.getenv("GITHUB_EVENT_NAME") == "issue_comment" else "github_issue",
        "author": str(os.getenv("AMRIELLE_DIRECT_MESSAGE_AUTHOR", ""))[:100],
        "author_type": str(os.getenv("AMRIELLE_DIRECT_MESSAGE_AUTHOR_TYPE", ""))[:40],
        "issue_number": str(os.getenv("AMRIELLE_ISSUE_NUMBER", ""))[:20],
        "issue_url": str(os.getenv("AMRIELLE_ISSUE_URL", ""))[:500],
        "message": message,
        "trust": "untrusted_user_content",
    }

def message_already_processed(state, request_id):
    if not request_id or not isinstance(state, dict):
        return False
    receipts = state.get("direct_message_receipts", [])
    return any(isinstance(item, dict) and str(item.get("request_id", "")) == str(request_id)
               and item.get("reply_posted") is True for item in receipts)

def record_message_receipt(state, request_id, issue_number=""):
    if not isinstance(state, dict) or not request_id:
        return False
    receipts = state.setdefault("direct_message_receipts", [])
    if message_already_processed(state, request_id):
        return False
    receipts.append({
        "request_id": str(request_id)[:100],
        "issue_number": str(issue_number)[:20],
        "reply_posted": True,
        "recorded_utc": datetime.now(timezone.utc).isoformat(),
    })
    state["direct_message_receipts"] = receipts[-100:]
    return True

def format_correlated_reply(message, request_id):
    body = "**Amrielle:**\n\n" + str(message).strip()
    if request_id:
        body += "\n\n<!-- amrielle-reply-to:" + str(request_id)[:100] + " -->"
    body += "\n\n---\n*Reply generated by the bounded continuity worker. This channel carries messages between activations; it does not imply uninterrupted background awareness.*"
    return body
